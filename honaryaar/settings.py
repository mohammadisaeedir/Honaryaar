def _neon_database():
    database_url = os.environ.get("DATABASE_URL")
    if database_url:
        url = urlparse(database_url)
        query = parse_qs(url.query)
        sslmode = (query.get("sslmode") or ["require"])[0]
        return {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": unquote(url.path.lstrip("/")),
            "USER": unquote(url.username or ""),
            "PASSWORD": unquote(url.password or ""),
            "HOST": url.hostname or "",
            "PORT": str(url.port or 5432),
            "OPTIONS": {"sslmode": sslmode},
            "CONN_HEALTH_CHECKS": True,
            "CONN_MAX_AGE": 60,
            "DISABLE_SERVER_SIDE_CURSORS": True,
        }

    host = os.environ.get("PGHOST", "")
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": os.environ.get("PGDATABASE", ""),
        "USER": os.environ.get("PGUSER", ""),
        "PASSWORD": os.environ.get("PGPASSWORD", ""),
        "HOST": host,
        "PORT": os.environ.get("PGPORT", "5432"),
        "OPTIONS": {"sslmode": "require"},
        "CONN_HEALTH_CHECKS": True,
        "CONN_MAX_AGE": 60,
        "DISABLE_SERVER_SIDE_CURSORS": True,
    }


def production_database(raw):
    """Connection for the live database. The session cannot write."""
    parsed = urlparse((raw or "").strip())
    database = unquote((parsed.path or "").lstrip("/"))
    if parsed.scheme not in {"postgres", "postgresql"} or not parsed.hostname or not database:
        raise ImproperlyConfigured("PROD_DATABASE_URL could not be parsed")
    sslmode = (parse_qs(parsed.query).get("sslmode") or ["require"])[0]
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": database,
        "USER": unquote(parsed.username or ""),
        "PASSWORD": unquote(parsed.password or ""),
        "HOST": parsed.hostname,
        "PORT": str(parsed.port or 5432),
        "OPTIONS": {
            "sslmode": sslmode,
            "options": "-c default_transaction_read_only=on",
        },
        "CONN_HEALTH_CHECKS": True,
        "CONN_MAX_AGE": 60,
        "DISABLE_SERVER_SIDE_CURSORS": True,
    }


def _database_from_env():
    # Prefer an explicit remote URL (Vercel Neon, VPS, etc.). Local Postgres
    # is used only when no remote connection is configured.
    if (
        os.environ.get("DATABASE_URL")
        or os.environ.get("VERCEL") == "1"
        or os.environ.get("PGHOST")
    ):
        return _neon_database()
    return _local_database()


